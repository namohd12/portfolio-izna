import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

await mkdir('.artifacts', { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const results = [];
for (const viewport of [{ width: 1440, height: 1000 }, { width: 768, height: 1024 }, { width: 390, height: 844 }, { width: 320, height: 740 }]) {
  const page = await browser.newPage({ viewport, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const response = await page.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle' });
  assert.equal(response.status(), 200);
  assert.match(await page.title(), /Nor Izna/);
  assert.equal(await page.locator('h1').count(), 1);
  assert.equal(await page.locator('.timeline-row').count(), 2);
  assert.equal(await page.locator('.project-card').count(), 3);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `Overflow at ${viewport.width}`);
  await page.locator('img').evaluateAll(images => Promise.all(images.map(image => { image.loading = 'eager'; return image.decode(); })));
  const invalidImages = await page.locator('img').evaluateAll(images => images.filter(i => !i.complete || i.naturalWidth === 0).map(i => i.src));
  assert.deepEqual(invalidImages, []);
  const anchors = await page.locator('a[href^="#"]').evaluateAll(links => links.filter(a => !document.querySelector(a.getAttribute('href'))).map(a => a.getAttribute('href')));
  assert.deepEqual(anchors, []);
  if (viewport.width <= 900) {
    const menu = page.locator('.menu-toggle');
    await menu.click();
    assert.equal(await menu.getAttribute('aria-expanded'), 'true');
    await page.keyboard.press('Escape');
    assert.equal(await menu.getAttribute('aria-expanded'), 'false');
    await menu.click();
    await page.getByRole('navigation').getByRole('link', { name: 'Experience', exact: true }).click();
    await page.waitForTimeout(150);
    assert.equal(await menu.getAttribute('aria-expanded'), 'false');
    assert.match(page.url(), /#experience$/);
  }
  const project = page.locator('.project-card').first();
  await project.getByRole('button').click();
  assert.equal(await project.getByRole('button').getAttribute('aria-expanded'), 'true');
  assert.equal(await project.locator('.project-detail').isVisible(), true);
  await project.getByRole('button').click();
  assert.equal(await project.locator('.project-detail').isVisible(), false);
  await page.locator('.leadership-details summary').click();
  assert.equal(await page.locator('.leadership-grid').isVisible(), true);
  await page.locator('.leadership-details summary').click();
  const downloadPromise = page.waitForEvent('download');
  await page.locator('.header-resume').click();
  const download = await downloadPromise;
  assert.match(download.suggestedFilename(), /Resume.pdf$/);
  assert.equal(await download.failure(), null);
  assert.equal(await page.getByRole('link', { name: 'Send an Email' }).getAttribute('href'), 'mailto:mnorizna@gmail.com');
  assert.equal(await page.locator('.contact-buttons a[target="_blank"]').getAttribute('href'), 'https://www.linkedin.com/in/izna-mohd');
  await page.getByRole('link', { name: 'Back to top' }).click();
  await page.waitForTimeout(150);
  assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).scrollBehavior), 'auto');
  await page.screenshot({ path: `.artifacts/portfolio-${viewport.width}.png`, fullPage: true });
  assert.deepEqual(errors, []);
  results.push(`${viewport.width}px: navigation, disclosures, download, images, anchors, reduced motion and overflow passed`);
  await page.close();
}
await browser.close();
console.log(results.join('\n'));
